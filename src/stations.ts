const title = (s: string) => s.toLowerCase().replace(/(^|[\s-])([а-яёa-z])/g, (_, a, b) => a + b.toUpperCase())

export interface KnownPlace { label: string; ll?: LatLng }

/** Станция из билета → понятное название и, если знаем, координаты. */
export function matchStation(raw: string): KnownPlace | null {
  const s = raw.trim()
  if (!s) return null
  for (const st of STATIONS) if (st.re.test(s)) return { label: st.label, ll: st.ll }
  return null
}

/** Как показать станцию из билета: «МОСКВА КАЗАНСКАЯ ПН» → «Москва, Казанский вокзал», «ТВЕРЬ» → «Тверь». */
export function prettyStation(raw: string): string {
  const m = matchStation(raw)
  if (m) return m.label
  const s = raw.trim()
  return s === s.toUpperCase() ? title(s).replace(/\s+(Пасс|Пн|Гл|Главн)\.?$/i, '') : s
}

