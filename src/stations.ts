/** Аэропорт по коду или по названию из таблицы («Самара, Курумоч»). */
export function matchAirport(raw: string): KnownPlace | null {
  const s = raw.trim()
  const code = /^[A-Z]{3}$/.test(s) ? s : Object.keys(AIRPORTS).find((c) => AIRPORTS[c].toLowerCase() === s.toLowerCase())
  if (!code || !AIRPORTS[code]) return null
  return { label: AIRPORTS[code], ll: AIRPORT_LL[code] }
}
